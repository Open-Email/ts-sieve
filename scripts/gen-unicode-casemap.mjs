// Generate the RFC 5051 preparation table from pinned Unicode 17.0 data.
// Usage: node scripts/gen-unicode-casemap.mjs [path/to/UnicodeData.txt]
// Input is data only; the checksum makes updates an explicit review decision.
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
const SOURCE = "https://www.unicode.org/Public/17.0.0/ucd/UnicodeData.txt";
const SHA256 = "2e1efc1dcb59c575eedf5ccae60f95229f706ee6d031835247d843c11d96470c";
const raw = process.argv[2] ? readFileSync(process.argv[2]) : Buffer.from(await (await fetch(SOURCE)).arrayBuffer());
if (createHash("sha256").update(raw).digest("hex") !== SHA256) throw new Error("UnicodeData checksum mismatch");
const data = new Map(raw.toString("utf8").trim().split("\n").map(line => {
  const f = line.split(";");
  return [parseInt(f[0], 16), { title: parseInt(f[14] || f[12] || f[0], 16), decomp: f[5].replace(/<[^>]+>\s*/, "").trim().split(/\s+/).filter(Boolean).map(cp => parseInt(cp, 16)) }];
}));
function decompose(cp) {
  if (cp >= 0xac00 && cp <= 0xd7a3) {
    const n = cp - 0xac00;
    return [0x1100 + Math.floor(n / 588), 0x1161 + Math.floor(n % 588 / 28), ...(n % 28 ? [0x11a7 + n % 28] : [])];
  }
  const d = data.get(cp)?.decomp;
  return d?.length ? d.flatMap(decompose) : [cp];
}
const rows = [];
let maxExpansion = 1;
for (const [cp, { title }] of data) {
  if (cp >= 0xac00 && cp <= 0xd7a3) continue; // algorithmic in the runtime
  const folded = decompose(title);
  maxExpansion = Math.max(maxExpansion, folded.length);
  if (folded.length === 1 && folded[0] === cp) continue;
  rows.push(`  [0x${cp.toString(16)}, "${folded.map(c => `\\u{${c.toString(16)}}`).join("")}"],`);
}
writeFileSync(new URL("../src/interp/unicode-casemap-data.ts", import.meta.url), `// GENERATED by scripts/gen-unicode-casemap.mjs — do not edit.
// Unicode 17.0.0: ${SOURCE}
// SHA-256: ${SHA256}
// Unicode data license: ../../LICENSE-UNICODE.txt
// Simple titlecase once, then recursive decomposition; no canonical reordering.
export const UNICODE_CASEMAP: ReadonlyMap<number, string> = new Map([\n${rows.join("\n")}\n]);
export const MAX_UNICODE_CASEMAP_EXPANSION = ${maxExpansion};\n`);
console.log(`${rows.length} mappings; maximum expansion ${maxExpansion}`);
