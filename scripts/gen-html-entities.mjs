// Regenerate src/interp/html-entities.ts from the WHATWG named character
// reference list — the table Go's html.UnescapeString embeds, which is what
// go-sieve's body :text decodes with.
//
//   node scripts/gen-html-entities.mjs
//
// The download is data, never code: every name must be [A-Za-z0-9]+ with an
// optional ";" and every value is written as \u{...} escapes.

import { createHash } from "node:crypto";
import { writeFileSync } from "node:fs";

const SOURCE = "https://html.spec.whatwg.org/entities.json";
// The list the committed table was generated from. A changed upstream list
// fails here, so updating the table is a reviewed decision: check the diff,
// then update this hash.
const SHA256 = "d741d877ac77c4194c4ad526b5b4a19aef8dfe411ab840a466891cdbb9f362e6";
const res = await fetch(SOURCE);
if (!res.ok) throw new Error(`${SOURCE}: HTTP ${res.status}`);
const raw = Buffer.from(await res.arrayBuffer());
const digest = createHash("sha256").update(raw).digest("hex");
if (digest !== SHA256) throw new Error(`${SOURCE} changed: sha256 ${digest}, expected ${SHA256}`);
const data = JSON.parse(raw.toString("utf8"));

const rows = [];
for (const [key, { codepoints }] of Object.entries(data)) {
  const name = key.slice(1); // drop "&"
  if (!/^[A-Za-z0-9]+;?$/.test(name)) throw new Error(`unexpected entity name: ${JSON.stringify(key)}`);
  if (!Array.isArray(codepoints) || codepoints.length < 1 || codepoints.length > 2) {
    throw new Error(`unexpected codepoints for ${key}`);
  }
  for (const cp of codepoints) {
    if (!Number.isInteger(cp) || cp < 0 || cp > 0x10ffff) throw new Error(`bad codepoint for ${key}`);
  }
  const value = codepoints.map((cp) => `\\u{${cp.toString(16)}}`).join("");
  rows.push([name, value]);
}
rows.sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));

const out = `// GENERATED by scripts/gen-html-entities.mjs from ${SOURCE} — do not edit.
//
// Every HTML named character reference: a name ending ";" is the standard
// form; a name without one is a legacy reference the HTML tokenizer also
// accepts bare (as Go's html.UnescapeString does).

export const HTML_ENTITIES: ReadonlyMap<string, string> = new Map([
${rows.map(([n, v]) => `  ["${n}", "${v}"],`).join("\n")}
]);

/** The longest legacy (no ";") name — the prefix search's upper bound. */
export const LONGEST_LEGACY_ENTITY = ${Math.max(...rows.filter(([n]) => !n.endsWith(";")).map(([n]) => n.length))};
`;
writeFileSync(new URL("../src/interp/html-entities.ts", import.meta.url), out);
console.log(`${rows.length} entities`);
