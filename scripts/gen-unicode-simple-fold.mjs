// Unicode 17.0 default simple case folding, for regex character semantics.
// Usage: node scripts/gen-unicode-simple-fold.mjs [path/to/CaseFolding.txt]
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
const SOURCE = "https://www.unicode.org/Public/17.0.0/ucd/CaseFolding.txt";
const SHA256 = "ff8d8fefbf123574205085d6714c36149eb946d717a0c585c27f0f4ef58c4183";
const raw = process.argv[2] ? readFileSync(process.argv[2]) : Buffer.from(await (await fetch(SOURCE)).arrayBuffer());
if (createHash("sha256").update(raw).digest("hex") !== SHA256) throw new Error("CaseFolding checksum mismatch");
const pairs = [];
for (const line of raw.toString("utf8").split("\n")) {
  const [cp, status, mapped] = line.split("#")[0].split(";").map(x => x.trim());
  if (status !== "C" && status !== "S") continue; // neither full nor Turkic mappings
  if (!/^[0-9A-F]+$/.test(cp) || !/^[0-9A-F]+$/.test(mapped)) throw new Error("Invalid simple mapping");
  pairs.push([parseInt(cp, 16), parseInt(mapped, 16)]);
}
const mapping = new Map(pairs);
for (const [, target] of pairs) if (mapping.has(target)) throw new Error("Non-canonical simple mapping");
writeFileSync(new URL("../src/interp/unicode-simple-fold-data.ts", import.meta.url), `// GENERATED by scripts/gen-unicode-simple-fold.mjs — do not edit.
// Unicode 17.0.0: ${SOURCE}
// SHA-256: ${SHA256}
// Default simple (C/S) case folding; Unicode data license: ../../LICENSE-UNICODE.txt
export const UNICODE_SIMPLE_FOLD: ReadonlyMap<number, number> = new Map([\n${pairs.map(([a,b]) => `  [0x${a.toString(16)}, 0x${b.toString(16)}],`).join("\n")}\n]);\n`);
console.log(`${pairs.length} simple case mappings`);
